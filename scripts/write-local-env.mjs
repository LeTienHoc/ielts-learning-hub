#!/usr/bin/env node
// Creates .env.local for local development from the running local Supabase stack.
// Run it yourself: `pnpm env:local` (add `--force` to overwrite an existing .env.local).
// Only the variables the app needs are written; key values are never printed.
//
// Windows + WSL: if 127.0.0.1 does not reach the stack (WSL localhost forwarding can be
// blocked, e.g. by VPN/firewall software), the current WSL IP is used instead. That IP
// changes when WSL restarts — re-run with --force. See docs/development/setup.md.

import { spawnSync } from "node:child_process"
import { existsSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const target = path.join(projectRoot, ".env.local")
const force = process.argv.includes("--force")

if (existsSync(target) && !force) {
  console.error(".env.local already exists. Re-run with --force to overwrite it.")
  process.exit(1)
}

const status = spawnSync(
  process.execPath,
  [path.join(projectRoot, "scripts/supabase.mjs"), "status", "-o", "env"],
  { cwd: projectRoot, encoding: "utf8" },
)
if (status.status !== 0) {
  console.error("Could not read local Supabase status. Is it running? Try `pnpm db:start`.")
  process.exit(1)
}

const values = Object.fromEntries(
  status.stdout
    .split(/\r?\n/)
    .map((line) => line.match(/^([A-Z_]+)="?(.*?)"?$/))
    .filter((match) => match !== null)
    .map((match) => [match[1], match[2]]),
)

if (!values.API_URL || !values.PUBLISHABLE_KEY) {
  console.error("Local Supabase status did not provide API_URL and PUBLISHABLE_KEY.")
  process.exit(1)
}

async function isReachable(url) {
  try {
    const response = await fetch(new URL("/auth/v1/health", url), {
      signal: AbortSignal.timeout(3000),
    })
    return response.ok
  } catch {
    return false
  }
}

function wslIp() {
  const result = spawnSync("wsl.exe", ["--exec", "hostname", "-I"], { encoding: "utf8" })
  return result.status === 0 ? result.stdout.trim().split(/\s+/)[0] : undefined
}

let host = new URL(values.API_URL).hostname
if (!(await isReachable(values.API_URL)) && process.platform === "win32") {
  const ip = wslIp()
  if (ip && (await isReachable(values.API_URL.replace(host, ip)))) {
    console.log(`127.0.0.1 is not forwarded from WSL; using the WSL IP ${ip} instead.`)
    host = ip
  }
}
const withHost = (url) => {
  const parsed = new URL(url)
  parsed.hostname = host
  return parsed.toString().replace(/\/$/, "")
}

if (!(await isReachable(withHost(values.API_URL)))) {
  console.error("The local Supabase API is not reachable. Check `pnpm db:status`.")
  process.exit(1)
}

const entries = {
  NEXT_PUBLIC_APP_URL: "http://localhost:3000",
  NEXT_PUBLIC_SUPABASE_URL: withHost(values.API_URL),
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: values.PUBLISHABLE_KEY,
  // Local email inbox used by E2E tests (not a secret).
  ...(values.MAILPIT_URL ? { MAILPIT_URL: withHost(values.MAILPIT_URL) } : {}),
}

const lines = [
  "# Generated by `pnpm env:local` for local development. Do not commit.",
  ...Object.entries(entries).map(([name, value]) => `${name}=${value}`),
  "",
]
writeFileSync(target, lines.join("\n"), { encoding: "utf8", flag: force ? "w" : "wx" })
console.log(`Wrote .env.local with: ${Object.keys(entries).join(", ")}`)
